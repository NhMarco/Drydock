//! Removes a provider's comments from an unlock Lua and puts Drydock's header on top — the same
//! cleaning the proxy gives every Lua it serves (`proxy/src/luaClean.ts`), for the one provider the
//! app talks to directly (Hubcap Manifest, with the user's own key).
//!
//! Providers decorate their Luas with banners, links, timestamps and disabled `setManifestid` lines.
//! None of it does anything; only comments go, found by a small Lua lexer so that `--` inside a
//! string is never mistaken for one. The result is deterministic, and cleaning it again changes
//! nothing — the header is a comment too, so it is stripped and written back identically.

/// The first lines of every cleaned Lua.
fn header(app_id: Option<u32>) -> [String; 2] {
    [
        app_id.map_or_else(
            || "-- Drydock unlock".to_owned(),
            |id| format!("-- Drydock unlock | App {id}"),
        ),
        "-- https://github.com/NhMarco/Drydock".to_owned(),
    ]
}

/// The level of a Lua long bracket opening at `index` (`[[` is 0, `[==[` is 2), if one does.
fn long_bracket_level(source: &[char], index: usize) -> Option<usize> {
    if source.get(index) != Some(&'[') {
        return None;
    }
    let mut cursor = index + 1;
    while source.get(cursor) == Some(&'=') {
        cursor += 1;
    }
    (source.get(cursor) == Some(&'[')).then(|| cursor - index - 1)
}

/// Just past where the long bracket of `level` closes, searching from `from`, or the end.
fn long_bracket_end(source: &[char], from: usize, level: usize) -> usize {
    let close: Vec<char> = std::iter::once(']')
        .chain(std::iter::repeat_n('=', level))
        .chain(std::iter::once(']'))
        .collect();
    (from..source.len())
        .find(|&start| source[start..].starts_with(&close))
        .map_or(source.len(), |start| start + close.len())
}

/// `source` without its comments; strings and long strings are copied as they are.
#[must_use]
pub fn strip_lua_comments(source: &str) -> String {
    let chars: Vec<char> = source.chars().collect();
    let mut out = String::with_capacity(source.len());
    let mut index = 0;
    while index < chars.len() {
        let char = chars[index];
        if char == '-' && chars.get(index + 1) == Some(&'-') {
            if let Some(level) = long_bracket_level(&chars, index + 2) {
                // --[[ … ]] and --[==[ … ]==]: a block comment, possibly in the middle of a line.
                index = long_bracket_end(&chars, index + 2 + level + 2, level);
            } else {
                // -- …: to the end of the line (the line break itself is kept).
                index = (index..chars.len())
                    .find(|&at| chars[at] == '\n')
                    .unwrap_or(chars.len());
            }
            continue;
        }
        if char == '"' || char == '\'' {
            // A quoted string, with its escapes, up to the closing quote or the end of the line.
            let mut end = index + 1;
            while end < chars.len() && chars[end] != char && chars[end] != '\n' {
                end += if chars[end] == '\\' { 2 } else { 1 };
            }
            let end = (end + 1).min(chars.len());
            out.extend(&chars[index..end]);
            index = end;
            continue;
        }
        if char == '['
            && let Some(level) = long_bracket_level(&chars, index)
        {
            let end = long_bracket_end(&chars, index + level + 2, level);
            out.extend(&chars[index..end]);
            index = end;
            continue;
        }
        out.push(char);
        index += 1;
    }
    out
}

/// The Lua as Drydock installs it: no provider comments, no empty lines, and Drydock's header on top.
#[must_use]
pub fn clean_lua(source: &str, app_id: Option<u32>) -> String {
    let source = source.strip_prefix('\u{feff}').unwrap_or(source);
    let code = strip_lua_comments(source);
    let lines = header(app_id).into_iter().chain(
        code.lines()
            .map(|line| line.trim_end().to_owned())
            .filter(|line| !line.trim().is_empty()),
    );
    let mut cleaned = lines.collect::<Vec<_>>().join("\n");
    cleaned.push('\n');
    cleaned
}

#[cfg(test)]
mod tests {
    use super::*;

    /// What providers actually wrap their Luas in: banners, links, timestamps, disabled pins, notes.
    const PROVIDER_LUA: &str = "\u{feff}-- Generated by SomeProvider.net | join discord.gg/someprovider\r\n\
-- Created: 2026-09-25 14:02:11\r\n\
--[[\r\n  Thanks for using our service!\r\n]]\r\n\
addappid(3751260) -- Main game\r\n\
addappid(3751261, 1, \"fe44cc16911c3d5dabb2b862a70f1b8b58ee79e1da1f47b8bf03af487c17e8fc\") --Mainappid\r\n\
-- setManifestid(3751261, \"6667172545766883229\")\r\n\
\r\n\
setManifestid(3751261, \"6667172545766883229\", 0)\r\n\
addtoken(3751260, \"a--b\") --[==[ note ]==] addappid(1)\r\n";

    #[test]
    fn provider_comments_go_and_the_code_stays() {
        assert_eq!(
            clean_lua(PROVIDER_LUA, Some(3_751_260)),
            "-- Drydock unlock | App 3751260\n\
-- https://github.com/NhMarco/Drydock\n\
addappid(3751260)\n\
addappid(3751261, 1, \"fe44cc16911c3d5dabb2b862a70f1b8b58ee79e1da1f47b8bf03af487c17e8fc\")\n\
setManifestid(3751261, \"6667172545766883229\", 0)\n\
addtoken(3751260, \"a--b\")  addappid(1)\n"
        );
    }

    #[test]
    fn cleaning_twice_changes_nothing() {
        let once = clean_lua(PROVIDER_LUA, Some(3_751_260));
        assert_eq!(clean_lua(&once, Some(3_751_260)), once);
        assert!(clean_lua("addappid(1)", None).starts_with("-- Drydock unlock\n"));
    }

    #[test]
    fn strings_and_long_strings_keep_their_dashes() {
        assert_eq!(strip_lua_comments("x = '--' -- c"), "x = '--' ");
        assert_eq!(strip_lua_comments("x = [[a -- b]] -- c"), "x = [[a -- b]] ");
        assert_eq!(strip_lua_comments("a --[[ open"), "a ");
    }
}
